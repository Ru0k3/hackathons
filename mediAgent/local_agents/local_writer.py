"""
Local Writer Agent - non-LLM fallback for offline or testing
Generates a simple markdown report from research data and triage output.
"""
from typing import Dict, Callable


class LocalWriterAgent:
    def __init__(self, status_callback: Callable[[str], None] = None):
        self.status_callback = status_callback

    def _log(self, msg: str):
        if self.status_callback:
            self.status_callback(msg)

    def create_report(self, research_data: Dict, triage_result: Dict = None, status_callback: Callable[[str], None] = None) -> str:
        cb = status_callback or self.status_callback
        if cb:
            cb(f"(local) Creating report for topic: {research_data.get('topic')}")

        lines = []
        lines.append(f"# Research Report: {research_data.get('topic', 'Unknown')}")
        lines.append("")
        lines.append("## Summary")
        lines.append(research_data.get('analysis', 'No analysis available'))
        lines.append("")

        if research_data.get('sources'):
            lines.append("## Sources")
            for idx, s in enumerate(research_data.get('sources', []), 1):
                lines.append(f"{idx}. {s.get('title', 'N/A')} - {s.get('url', 'N/A')}")
            lines.append("")

        if triage_result:
            lines.append("## Triage Result")
            lines.append(f"- Decision: {triage_result.get('decision')}")
            lines.append(f"- Reason: {triage_result.get('decision_reason')}")
            lines.append("")

        lines.append("---")
        lines.append("Generated by LocalWriterAgent")

        report = "\n".join(lines)
        if cb:
            cb("(local) Report creation complete")
        return report
