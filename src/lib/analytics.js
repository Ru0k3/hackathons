// frontend/src/lib/analytics.js
/**
 * Modeon — Typed Analytics Event Functions
 *
 * Every function wraps posthog.capture() in try/catch.
 * Analytics failures NEVER propagate — the UI is always unaffected.
 *
 * Event names and property keys match the catalogue in ai_rules.md exactly.
 * Do not rename event strings or property keys without updating both files.
 */

import { posthog } from './posthog'

/**
 * Internal helper — safely fire a PostHog event.
 * @param {string} event
 * @param {Record<string, unknown>} [properties]
 */
function capture(event, properties = {}) {
  try {
    posthog.capture(event, properties)
  } catch (_) {
    // Silent — analytics must never crash the UI
  }
}

